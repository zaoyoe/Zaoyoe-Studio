#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');
const sharp = require('sharp');

const ROOT_DIR = path.resolve(__dirname, '..');
const SERVER_ENV_PATH = path.join(ROOT_DIR, 'server/.env');
const LOCAL_ENV_PATH = path.join(ROOT_DIR, '.env.local');
const PROMPT_SOURCE_DIR = path.join(ROOT_DIR, 'assets/prompts');
const PROMPT_VARIANTS = [
    {
        id: 'home',
        outputDir: path.join(ROOT_DIR, 'assets/prompts-home'),
        publicDir: '/assets/prompts-home',
        width: 420,
        quality: 74
    },
    {
        id: 'card',
        outputDir: path.join(ROOT_DIR, 'assets/prompts-card'),
        publicDir: '/assets/prompts-card',
        width: 560,
        quality: 76
    },
    {
        id: 'featured',
        outputDir: path.join(ROOT_DIR, 'assets/prompts-featured'),
        publicDir: '/assets/prompts-featured',
        width: 1280,
        quality: 80
    }
];
const PRODUCT_CARD_VARIANT = {
    id: 'card',
    outputDir: path.join(ROOT_DIR, 'assets/products-card'),
    publicDir: '/assets/products-card',
    width: 480,
    height: 320,
    quality: 78
};
const PROMPT_MANIFEST_PATH = path.join(ROOT_DIR, 'js/prompt-image-variants.js');
const SHOP_MANIFEST_PATH = path.join(ROOT_DIR, 'js/shop-image-variants.js');
const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp']);

function readEnvFile(filePath) {
    if (!fs.existsSync(filePath)) {
        return {};
    }

    return dotenv.parse(fs.readFileSync(filePath, 'utf8'));
}

function readFirstEnv(sources, names, fallback = '') {
    for (const source of sources) {
        for (const name of names) {
            const value = String(source?.[name] || '').trim();
            if (value) return value;
        }
    }
    return fallback;
}

function parseArgs(argv = []) {
    const args = {
        prompts: true,
        products: false,
        dryRun: false,
        activeProductsOnly: true,
        productLimit: Infinity
    };

    for (let index = 0; index < argv.length; index += 1) {
        const value = String(argv[index] || '').trim();
        if (!value) continue;

        if (value === '--products') {
            args.products = true;
            continue;
        }
        if (value === '--prompts-only') {
            args.prompts = true;
            args.products = false;
            continue;
        }
        if (value === '--products-only') {
            args.prompts = false;
            args.products = true;
            continue;
        }
        if (value === '--include-inactive-products') {
            args.activeProductsOnly = false;
            continue;
        }
        if (value === '--dry-run') {
            args.dryRun = true;
            continue;
        }
        if (value === '--product-limit') {
            const limit = Number.parseInt(argv[index + 1], 10);
            if (Number.isFinite(limit) && limit > 0) {
                args.productLimit = limit;
            }
            index += 1;
        }
    }

    return args;
}

function ensureDir(dirPath, dryRun = false) {
    if (dryRun || fs.existsSync(dirPath)) {
        return;
    }
    fs.mkdirSync(dirPath, { recursive: true });
}

function listPromptSourceFiles() {
    if (!fs.existsSync(PROMPT_SOURCE_DIR)) {
        return [];
    }

    return fs.readdirSync(PROMPT_SOURCE_DIR)
        .filter((filename) => IMAGE_EXTENSIONS.has(path.extname(filename).toLowerCase()))
        .sort((a, b) => a.localeCompare(b));
}

function getOutputFilename(sourceFilename) {
    return `${path.basename(sourceFilename, path.extname(sourceFilename))}.webp`;
}

async function buildPromptVariant(sourcePath, outputPath, variant) {
    return sharp(sourcePath, { failOn: 'none' })
        .rotate()
        .resize(variant.width, null, {
            fit: 'inside',
            withoutEnlargement: true
        })
        .webp({
            quality: variant.quality,
            effort: 5
        })
        .toFile(outputPath);
}

function writePromptManifest(variantFilesById, dryRun = false) {
    const payload = {
        version: '20260430_RESPONSIVE_IMAGE_VARIANTS_1',
        basePaths: PROMPT_VARIANTS.reduce((acc, variant) => {
            acc[variant.id] = variant.publicDir;
            return acc;
        }, {}),
        variants: variantFilesById
    };
    const source = `// Generated by scripts/generate-responsive-image-variants.js\n(function () {\n    'use strict';\n\n    window.__PROMPT_IMAGE_VARIANTS__ = Object.freeze(${JSON.stringify(payload, null, 4)});\n}());\n`;

    if (dryRun) {
        console.log(`[dry-run] would write ${path.relative(ROOT_DIR, PROMPT_MANIFEST_PATH)}`);
        return;
    }

    fs.writeFileSync(PROMPT_MANIFEST_PATH, source);
}

async function generatePromptVariants(options = {}) {
    const { dryRun = false } = options;
    const sourceFiles = listPromptSourceFiles();
    const variantFilesById = Object.fromEntries(PROMPT_VARIANTS.map((variant) => [variant.id, []]));

    console.log(`🖼️  Prompt responsive variants: ${sourceFiles.length} source images`);

    for (const variant of PROMPT_VARIANTS) {
        ensureDir(variant.outputDir, dryRun);
    }

    for (const sourceFilename of sourceFiles) {
        const sourcePath = path.join(PROMPT_SOURCE_DIR, sourceFilename);
        const outputFilename = getOutputFilename(sourceFilename);

        for (const variant of PROMPT_VARIANTS) {
            const outputPath = path.join(variant.outputDir, outputFilename);
            variantFilesById[variant.id].push(outputFilename);

            if (dryRun) {
                continue;
            }

            await buildPromptVariant(sourcePath, outputPath, variant);
        }
    }

    Object.keys(variantFilesById).forEach((variantId) => {
        variantFilesById[variantId] = [...new Set(variantFilesById[variantId])].sort((a, b) => a.localeCompare(b));
    });
    writePromptManifest(variantFilesById, dryRun);
}

function normalizeProductVariantFilename(product) {
    const id = String(product?.id || '').trim();
    if (id) {
        return `${id}.webp`;
    }
    const sourceUrl = String(product?.icon_url || '').trim();
    const parsed = new URL(sourceUrl);
    const basename = path.basename(parsed.pathname).replace(/\.[^.]+$/, '');
    return `${basename || 'product'}.webp`;
}

function isProductImageSource(value) {
    const source = String(value || '').trim();
    return source.startsWith('http://') || source.startsWith('https://');
}

async function downloadBuffer(url) {
    const response = await fetch(url);
    if (!response.ok) {
        throw new Error(`HTTP ${response.status}`);
    }
    return Buffer.from(await response.arrayBuffer());
}

async function buildProductCardVariant(sourceBuffer, outputPath, variant) {
    return sharp(sourceBuffer, { failOn: 'none' })
        .rotate()
        .resize(variant.width, variant.height, {
            fit: 'cover',
            position: 'center',
            withoutEnlargement: false
        })
        .webp({
            quality: variant.quality,
            effort: 5
        })
        .toFile(outputPath);
}

async function fetchProducts(options = {}) {
    const envSources = [
        process.env,
        readEnvFile(LOCAL_ENV_PATH),
        readEnvFile(SERVER_ENV_PATH)
    ];
    const supabaseUrl = readFirstEnv(envSources, ['SUPABASE_URL', 'NEXT_PUBLIC_SUPABASE_URL', 'PUBLIC_SUPABASE_URL']);
    const supabaseKey = readFirstEnv(envSources, [
        'SUPABASE_SERVICE_ROLE_KEY',
        'SUPABASE_PUBLISHABLE_KEY',
        'NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY',
        'SUPABASE_ANON_KEY',
        'NEXT_PUBLIC_SUPABASE_ANON_KEY'
    ]);

    if (!supabaseUrl || !supabaseKey) {
        throw new Error('Missing Supabase URL/key for product image variants');
    }

    const { createClient } = require('@supabase/supabase-js');
    const supabase = createClient(supabaseUrl, supabaseKey, {
        auth: {
            persistSession: false,
            autoRefreshToken: false
        }
    });

    let query = supabase
        .from('shop_products')
        .select('id, name, icon_url, is_active')
        .not('icon_url', 'is', null)
        .order('display_order', { ascending: false });

    if (options.activeProductsOnly !== false) {
        query = query.eq('is_active', true);
    }

    if (Number.isFinite(options.productLimit)) {
        query = query.limit(options.productLimit);
    }

    const { data, error } = await query;
    if (error) {
        throw error;
    }
    return Array.isArray(data) ? data : [];
}

function writeShopManifest(cardMap, dryRun = false) {
    const payload = {
        version: '20260430_RESPONSIVE_IMAGE_VARIANTS_1',
        basePaths: {
            card: PRODUCT_CARD_VARIANT.publicDir
        },
        variants: {
            card: cardMap
        }
    };
    const source = `// Generated by scripts/generate-responsive-image-variants.js\n(function () {\n    'use strict';\n\n    window.__SHOP_IMAGE_VARIANTS__ = Object.freeze(${JSON.stringify(payload, null, 4)});\n}());\n`;

    if (dryRun) {
        console.log(`[dry-run] would write ${path.relative(ROOT_DIR, SHOP_MANIFEST_PATH)}`);
        return;
    }

    fs.writeFileSync(SHOP_MANIFEST_PATH, source);
}

async function generateProductVariants(options = {}) {
    const { dryRun = false } = options;
    const products = (await fetchProducts(options))
        .filter((product) => isProductImageSource(product?.icon_url));
    const cardMap = {};

    console.log(`🛒 Product card variants: ${products.length} product images`);
    ensureDir(PRODUCT_CARD_VARIANT.outputDir, dryRun);

    for (const product of products) {
        const sourceUrl = String(product.icon_url || '').trim();
        const outputFilename = normalizeProductVariantFilename(product);
        const outputPath = path.join(PRODUCT_CARD_VARIANT.outputDir, outputFilename);
        cardMap[sourceUrl] = `${PRODUCT_CARD_VARIANT.publicDir}/${outputFilename}`;

        if (dryRun) {
            continue;
        }

        try {
            const sourceBuffer = await downloadBuffer(sourceUrl);
            await buildProductCardVariant(sourceBuffer, outputPath, PRODUCT_CARD_VARIANT);
        } catch (error) {
            console.warn(`⚠️  Failed product image variant for ${product.name || product.id}: ${error.message}`);
            delete cardMap[sourceUrl];
        }
    }

    writeShopManifest(cardMap, dryRun);
}

async function main() {
    const args = parseArgs(process.argv.slice(2));

    if (args.prompts) {
        await generatePromptVariants(args);
    }

    if (args.products) {
        await generateProductVariants(args);
    }

    console.log('✅ Responsive image variant generation complete');
}

main().catch((error) => {
    console.error('❌ Responsive image variant generation failed:', error);
    process.exit(1);
});
