const ROOT = path.resolve(__dirname, '..');

function readRepoFile(relativePath) {
    return fs.readFileSync(path.join(ROOT, relativePath), 'utf8');
}

function readJsBlock(source, startNeedle, endNeedle) {
    const start = source.indexOf(startNeedle);
    assert.notEqual(start, -1, `Missing block start: ${startNeedle}`);
    const bodyStart = start + startNeedle.length;
    const end = source.indexOf(endNeedle, bodyStart);
    assert.notEqual(end, -1, `Missing block end for: ${startNeedle}`);
    return source.slice(bodyStart, end);
}

function readQuotedValues(block) {
    return [...block.matchAll(/'([^']+)'/g)].map((match) => match[1]);
}

